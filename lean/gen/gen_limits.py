"""Generate Frobenius/K4LimitsData.lean: polynomial bounds behind Corollary 1.5.

For every class r and x >= 1 it proves, with Phi_r = P_r / d_r and Gam_r = G_r / e_r
(integer division, as defined in K4Phi.lean and K4GP.lean):
  9 x^6 - KF x^5 <= 5 phi_r x <= 26 x^6 + KF x^5,
  97 x^6 - KG x^5 <= 100 gam_r x,   5 gam_r x <= 13 x^6 + KG x^5,
and the sharp bounds 5 phi15 x <= 9 x^6 + KF x^5, 26 x^6 - KF x^5 <= 5 phi39 x,
100 gam15 x <= 97 x^6 + KG x^5, 13 x^6 - KG x^5 <= 5 gam39 x.
The polynomials are read from the Lean sources, so they are the ones used in the formal proofs.
"""
import re, os, math
from fractions import Fraction as Fr
import sympy as sp

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'Frobenius')
x = sp.Symbol('x')

texts = {}
def read(fname, name):
    out = {}
    for m in re.finditer(r'def ' + name + r'(\d+) \(x : ℤ\) : ℤ := \((.*)\) / (\d+)',
                         open(os.path.join(src, fname), encoding='utf-8').read()):
        r, P, d = int(m.group(1)), m.group(2), int(m.group(3))
        poly = sp.Poly(sp.sympify(P.replace('^', '**')), x)
        out[r] = ([int(poly.coeff_monomial(x**i)) for i in range(7)], d)
        texts[(name, r)] = P
    assert sorted(out) == list(range(40)), (name, sorted(out))
    return out

phi = read('K4Phi.lean', 'phi')
gam = read('K4GP.lean', 'gam')

def need_lo(co, d, M, L):
    # M*q >= L x^6 - K x^5 where d q > P - d
    assert M * co[6] >= d * L, (co, d, M, L)
    neg = sum(-c for c in co[:6] if c < 0)
    return Fr(M * (neg + d), d)

def need_hi(co, d, M, L):
    # M*q <= L x^6 + K x^5 where d q <= P
    assert M * co[6] <= d * L, (co, d, M, L)
    pos = sum(c for c in co[:6] if c > 0)
    return Fr(M * pos, d)

KF = max(max(need_lo(*phi[r], 5, 9), need_hi(*phi[r], 5, 26)) for r in range(40))
KF = max(KF, need_hi(*phi[15], 5, 9), need_lo(*phi[39], 5, 26))
KG = max(max(need_lo(*gam[r], 100, 97), need_hi(*gam[r], 5, 13)) for r in range(40))
KG = max(KG, need_hi(*gam[15], 100, 97), need_lo(*gam[39], 5, 13))
KF, KG = math.ceil(KF) + 1, math.ceil(KG) + 1

def lemma(name, fn, r, d, kind, M, L, K):
    P = f'{fn}{r}'
    E = texts[(fn, r)]
    if kind == 'lo':
        stmt = f'{L} * x ^ 6 - {K} * x ^ 5 ≤ {M} * {P} x'
        fact = f'have h : {E} < {d} * {P} x + {d} := Int.lt_mul_ediv_self_add (by norm_num)'
    else:
        stmt = f'{M} * {P} x ≤ {L} * x ^ 6 + {K} * x ^ 5'
        fact = f'have h : {P} x * {d} ≤ {E} := Int.ediv_mul_le _ (by norm_num)'
    return (f'theorem {name} (x : ℤ) (hx : 1 ≤ x) : {stmt} := by\n'
            f'  obtain ⟨p6, p5, p4, p3, p2, p1, q0, q1, q2, q3, q4⟩ := pow_facts x hx\n'
            f'  {fact}\n'
            f'  simp only [{K}]\n'
            f'  linarith\n')

out = ['import Frobenius.K4\n',
       '/-!\n# Polynomial bounds for Corollary 1.5 (generated by `gen/gen_limits.py`)\n-/\n',
       'namespace FrobK4\n',
       f'/-- The constant `K` for the Frobenius number. -/\ndef KF : ℤ := {KF}\n',
       f'/-- The constant `K` for the genus. -/\ndef KG : ℤ := {KG}\n',
       '''theorem pow_facts (x : ℤ) (hx : 1 ≤ x) :
    0 ≤ x ^ 6 ∧ 0 ≤ x ^ 5 ∧ 0 ≤ x ^ 4 ∧ 0 ≤ x ^ 3 ∧ 0 ≤ x ^ 2 ∧ 0 ≤ x ∧
    1 ≤ x ^ 5 ∧ x ≤ x ^ 5 ∧ x ^ 2 ≤ x ^ 5 ∧ x ^ 3 ≤ x ^ 5 ∧ x ^ 4 ≤ x ^ 5 := by
  have h0 : (0 : ℤ) ≤ x := by omega
  refine ⟨by positivity, by positivity, by positivity, by positivity, by positivity, h0,
    one_le_pow₀ hx, ?_, ?_, ?_, ?_⟩
  · simpa using pow_le_pow_right₀ hx (show 1 ≤ 5 by norm_num)
  · exact pow_le_pow_right₀ hx (by norm_num)
  · exact pow_le_pow_right₀ hx (by norm_num)
  · exact pow_le_pow_right₀ hx (by norm_num)
''']
for r in range(40):
    co, d = phi[r]
    out.append(lemma(f'phi{r}_lo', 'phi', r, d, 'lo', 5, 9, 'KF'))
    out.append(lemma(f'phi{r}_hi', 'phi', r, d, 'hi', 5, 26, 'KF'))
    co, d = gam[r]
    out.append(lemma(f'gam{r}_lo', 'gam', r, d, 'lo', 100, 97, 'KG'))
    out.append(lemma(f'gam{r}_hi', 'gam', r, d, 'hi', 5, 13, 'KG'))
out.append(lemma('phi15_sharp', 'phi', 15, phi[15][1], 'hi', 5, 9, 'KF'))
out.append(lemma('phi39_sharp', 'phi', 39, phi[39][1], 'lo', 5, 26, 'KF'))
out.append(lemma('gam15_sharp', 'gam', 15, gam[15][1], 'hi', 100, 97, 'KG'))
out.append(lemma('gam39_sharp', 'gam', 39, gam[39][1], 'lo', 5, 13, 'KG'))

def agg(name, fn, Fn, kind, M, L, K):
    if kind == 'lo':
        stmt = f'{L} * (n : ℤ) ^ 6 - {K} * (n : ℤ) ^ 5 ≤ {M} * {Fn} n'
    else:
        stmt = f'{M} * {Fn} n ≤ {L} * (n : ℤ) ^ 6 + {K} * (n : ℤ) ^ 5'
    s = (f'theorem {name} (n : ℕ) (hn : 1 ≤ n) : {stmt} := by\n'
         f'  have hx : (1 : ℤ) ≤ n := by exact_mod_cast hn\n'
         f'  have hr : n % 40 < 40 := Nat.mod_lt _ (by norm_num)\n'
         f'  unfold {Fn}\n'
         f'  generalize n % 40 = r at hr ⊢\n'
         f'  interval_cases r\n')
    for r in range(40):
        s += f'  · exact {fn}{r}_{kind} _ hx\n'
    return s
out.append(agg('Phi_lo', 'phi', 'Phi', 'lo', 5, 9, 'KF'))
out.append(agg('Phi_hi', 'phi', 'Phi', 'hi', 5, 26, 'KF'))
out.append(agg('Gam_lo', 'gam', 'Gam', 'lo', 100, 97, 'KG'))
out.append(agg('Gam_hi', 'gam', 'Gam', 'hi', 5, 13, 'KG'))
out.append('end FrobK4\n')
open(os.path.join(src, 'K4LimitsData.lean'), 'w', encoding='utf-8').write('\n'.join(out))
print('KF =', KF, ' KG =', KG)
